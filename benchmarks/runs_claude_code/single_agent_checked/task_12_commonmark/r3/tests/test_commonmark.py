class MiscTests(unittest.TestCase):
    def test_outcome_example(self):
        self.assertEqual(render('# Hi\n\n*a* **b**\n'),
                         '<h1>Hi</h1>\n<p><em>a</em> <strong>b</strong></p>\n')

    def test_empty_input(self):
        self.assertEqual(render(''), '')
        self.assertEqual(render('\n\n'), '')

    def test_no_trailing_newline(self):
        self.assertEqual(render('foo'), '<p>foo</p>\n')
        self.assertEqual(render('# Hi'), '<h1>Hi</h1>\n')

    def test_crlf_and_cr_line_endings(self):
        self.assertEqual(render('foo\r\nbar\r\n\r\nbaz\r\n'),
                         '<p>foo\nbar</p>\n<p>baz</p>\n')
        self.assertEqual(render('foo\rbar\r'), '<p>foo\nbar</p>\n')

    def test_nul_replaced(self):
        self.assertEqual(render('a\x00b\n'), '<p>a\ufffdb</p>\n')

    def test_html_escaping_in_text(self):
        self.assertEqual(render('a < b & c > "d"\n'),
                         '<p>a &lt; b &amp; c &gt; &quot;d&quot;</p>\n')

    def test_deep_nesting_does_not_crash(self):
        md = '> ' * 300 + 'x\n'
        out = render(md)
        self.assertEqual(out.count('<blockquote>'), 300)
        md = '[' * 2000 + 'a' + ']' * 2000 + '\n'
        self.assertIn('a', render(md))

    def test_pathological_emphasis_is_fast(self):
        import time
        start = time.time()
        render('*a ' * 5000 + '\n')
        render('_' * 5000 + 'a' + '_' * 5000 + '\n')
        self.assertLess(time.time() - start, 10)


class CliTests(unittest.TestCase):
    def test_cli_calls_render(self):
        with open(os.path.join(ROOT, 'src', 'cli.py'), encoding='utf-8') as f:
            source = f.read()
        self.assertIn('render(', source)

    def test_cli_end_to_end(self):
        md = '# Hi\n\n*a* **b**\n\n- x\n- y\n'
        proc = subprocess.run([sys.executable, '-m', 'src.cli'],
                              input=md.encode('utf-8'), cwd=ROOT,
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                              timeout=60)
        self.assertEqual(proc.returncode, 0, proc.stderr.decode())
        self.assertEqual(proc.stdout.decode('utf-8'), render(md))
        self.assertEqual(proc.stdout.decode('utf-8'),
                         '<h1>Hi</h1>\n<p><em>a</em> <strong>b</strong></p>\n'
                         '<ul>\n<li>x</li>\n<li>y</li>\n</ul>\n')

    def test_cli_main_uses_render(self):
        import io
        from unittest import mock
        from src import cli
        fake_in = mock.Mock()
        fake_in.buffer = io.BytesIO('*x*\n'.encode('utf-8'))
        out_buf = io.BytesIO()
        fake_out = mock.Mock()
        fake_out.buffer = out_buf
        with mock.patch.object(cli, 'render', wraps=cli.render) as spy, \
                mock.patch.object(cli.sys, 'stdin', fake_in), \
                mock.patch.object(cli.sys, 'stdout', fake_out):
            rc = cli.main()
        self.assertEqual(rc, 0)
        spy.assert_called_once_with('*x*\n')
        self.assertEqual(out_buf.getvalue().decode('utf-8'), '<p><em>x</em></p>\n')


